#!/usr/bin/env python3
"""Reproduce pinned Mermaid/font assets; verify npm integrity and record SHA-256."""
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import tarfile
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets'
FONTS = [
    ('inter', '5.3.0', 'Inter'),
    ('source-serif-4', '5.3.1', 'Source Serif 4'),
    ('merriweather', '5.3.0', 'Merriweather'),
    ('ibm-plex-sans', '5.3.0', 'IBM Plex Sans'),
    ('jetbrains-mono', '5.3.0', 'JetBrains Mono'),
    ('noto-sans', '5.3.0', 'Noto Sans'),
    ('noto-sans-sc', '5.3.1', 'Noto Sans CJK SC'),
]
manifest = []


def package(name, version):
    with urlopen(f'https://registry.npmjs.org/{name}/{version}', timeout=30) as response:
        metadata = json.load(response)
    with urlopen(metadata['dist']['tarball'], timeout=60) as response:
        archive = response.read()
    algorithm, digest = metadata['dist']['integrity'].split('-', 1)
    assert base64.b64encode(hashlib.new(algorithm, archive).digest()).decode() == digest
    manifest.append({'package': name, 'version': version,
                     'url': metadata['dist']['tarball'],
                     'integrity': metadata['dist']['integrity'],
                     'license': metadata['license'], 'files': {}})
    return tarfile.open(fileobj=io.BytesIO(archive)), metadata


def write(relative, data):
    path = ASSETS / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    manifest[-1]['files'][relative] = hashlib.sha256(data).hexdigest()


if __name__ == '__main__':
    archive, metadata = package('mermaid', '11.17.2')
    assert metadata['license'] == 'MIT'
    for source, destination in [('dist/mermaid.min.js', 'mermaid.min.js'),
                                ('LICENSE', 'LICENSE'), ('package.json', 'package.json')]:
        write('vendor/mermaid/' + destination, archive.extractfile('package/' + source).read())
    archive.close()
    css_parts = ['/* Generated by scripts/vendor_assets.py; local OFL variable fonts. */\n']
    for slug, version, family in FONTS:
        archive, metadata = package('@fontsource-variable/' + slug, version)
        assert metadata['license'] == 'OFL-1.1'
        license_text = archive.extractfile('package/LICENSE').read()
        assert b'SIL OPEN FONT LICENSE' in license_text.upper()
        write(f'fonts/{slug}/OFL.txt', license_text)
        for style in ['wght.css', 'wght-italic.css']:
            try:
                css = archive.extractfile('package/' + style).read().decode()
            except KeyError:
                if style == 'wght.css':
                    raise
                continue
            for filename in re.findall(r'url\(\./files/([^\)]+)\)', css):
                data = archive.extractfile('package/files/' + filename).read()
                assert data[:4] == b'wOF2', filename
                write(f'fonts/{slug}/{filename}', data)
            css = re.sub(r"font-family: '[^']+'", f"font-family: '{family}'", css)
            css = css.replace('font-display: swap', 'font-display: block')
            css = css.replace('url(./files/', f'url(/assets/fonts/{slug}/')
            css_parts.append(css)
        archive.close()
        print('Vendored', slug, version, flush=True)
    (ASSETS / 'fonts/fonts.css').write_text('\n'.join(css_parts))
    (ASSETS / 'vendor-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
